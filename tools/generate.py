from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "tools" / "telemetry_spec.txt"

BASIC = {
    "bool": (1, 1, "bool", "ctypes.c_bool", "bool", "bool"),
    "u32": (4, 4, "uint32_t", "ctypes.c_uint32", "int", "uint32"),
    "s32": (4, 4, "int32_t", "ctypes.c_int32", "int", "int32"),
    "u64": (8, 8, "uint64_t", "ctypes.c_uint64", "int", "uint64"),
    "s64": (8, 8, "int64_t", "ctypes.c_int64", "int", "int64"),
    "f32": (4, 4, "float", "ctypes.c_float", "float", "float32"),
    "f64": (8, 8, "double", "ctypes.c_double", "float", "float64"),
}


class Field:
    def __init__(self, name, type_, count, unit, bind, desc):
        self.name, self.type, self.count, self.unit, self.bind, self.desc = name, type_, count, unit, bind, desc

    @property
    def is_str(self) -> bool:
        return self.type.startswith("str:")

    @property
    def str_len(self) -> int:
        return int(self.type.split(":")[1])


class Struct:
    def __init__(self, name, prefix, desc):
        self.name, self.prefix, self.desc = name, prefix, desc
        self.fields: list[Field] = []


def load_spec() -> tuple[dict[str, int], list[Struct]]:
    consts: dict[str, int] = {}
    structs: list[Struct] = []
    for line_no, raw in enumerate(SPEC.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("//") or line.startswith("#"):
            continue
        if line.startswith("@const"):
            name, value = [p.strip() for p in line[6:].split("|")]
            consts[name] = int(value)
            continue
        if line.startswith("@struct"):
            parts = [p.strip() for p in line[7:].split("|", 2)]
            prefix = None if parts[1] == "inherit" else ("" if parts[1] == "empty" else parts[1])
            structs.append(Struct(parts[0], prefix, parts[2]))
            continue
        parts = [p.strip() for p in line.split("|", 4)]
        if len(parts) != 5 or not structs:
            print(f"{SPEC.name}:{line_no}: malformed line: {raw}")
            sys.exit(1)
        type_, count = parts[1], None
        if type_.endswith("]"):
            type_, n = type_[:-1].split("[")
            count = consts.get(n) or int(n)
        bind = None if parts[3] == "-" else tuple(parts[3].split(":"))
        structs[-1].fields.append(Field(parts[0], type_, count, parts[2], bind, parts[4]))
    return consts, structs


CONSTS, STRUCTS_LIST = load_spec()
STRUCTS = {s.name: s for s in STRUCTS_LIST}
_layouts: dict[str, dict] = {}


def size_align(fld: Field) -> tuple[int, int]:
    if fld.type in BASIC:
        return BASIC[fld.type][0], BASIC[fld.type][1]
    if fld.is_str:
        return fld.str_len, 1
    lay = layout(fld.type)
    return lay["size"], lay["align"]


def layout(name: str) -> dict:
    if name in _layouts:
        return _layouts[name]
    items = []
    off, align, pad_no = 0, 1, 0
    for fld in STRUCTS[name].fields:
        sz, al = size_align(fld)
        align = max(align, al)
        if off % al:
            pad = al - off % al
            items.append(("pad", f"_pad{pad_no}", off, pad))
            pad_no += 1
            off += pad
        items.append(("field", fld, off, sz * (fld.count or 1)))
        off += sz * (fld.count or 1)
    if off % align:
        items.append(("pad", f"_pad{pad_no}", off, align - off % align))
        off += align - off % align
    _layouts[name] = {"items": items, "size": off, "align": align}
    return _layouts[name]


def const_cpp_name(name: str) -> str:
    return "k" + "".join(p.capitalize() for p in name.split("_"))


def doc_line(fld: Field) -> str:
    return fld.desc + (f" Unit: {fld.unit}." if fld.unit else "")


def doc_type(fld: Field) -> str:
    if fld.type in BASIC:
        base = BASIC[fld.type][5]
    elif fld.is_str:
        base = f"string[{fld.str_len}]"
    else:
        base = f"`{fld.type}`"
    return base + (f" x {fld.count}" if fld.count else "")


def main() -> None:
    write_cpp_header()
    write_python()
    write_markdown()
    write_bindings()
    print(f"{len(STRUCTS_LIST)} structs generated, TelemetryData is {layout('TelemetryData')['size']} bytes")


def write_cpp_header() -> None:
    out = [
        "// Generated by tools/generate.py",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace ets2la_telemetry {",
        "",
        'static_assert(sizeof(bool) == 1, "bool must be one byte");',
        "",
    ]
    for name, value in CONSTS.items():
        out += [f"// Array size used by the telemetry data ({name.lower().replace('_', ' ')}).",
                f"constexpr uint32_t {const_cpp_name(name)} = {value};", ""]
    for st in STRUCTS_LIST:
        lay = layout(st.name)
        out += [f"// {st.desc}", f"struct {st.name} {{"]
        for kind, item, off, size in lay["items"]:
            if kind == "pad":
                out.append(f"    uint8_t {item}[{size}];  // Explicit padding, always 0.")
                continue
            fld = item
            if fld.type in BASIC:
                ctype = BASIC[fld.type][2]
            else:
                ctype = "char" if fld.is_str else fld.type
            if fld.is_str:
                dims = f"[{fld.count}][{fld.str_len}]" if fld.count else f"[{fld.str_len}]"
            else:
                dims = f"[{fld.count}]" if fld.count else ""
            out.append(f"    {ctype} {fld.name}{dims};  // {doc_line(fld)}")
        out += ["};", ""]
        out.append(f'static_assert(sizeof({st.name}) == {lay["size"]}, "{st.name} layout");')
        for kind, item, off, size in lay["items"]:
            if kind == "field":
                out.append(f'static_assert(offsetof({st.name}, {item.name}) == {off}, "{st.name} layout");')
        out.append("")
    out += ["}"]
    path = ROOT / "include" / "ets2la_telemetry" / "telemetry_data.h"
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")


def py_ctype(fld: Field) -> str:
    if fld.type in BASIC:
        base = BASIC[fld.type][3]
    elif fld.is_str:
        base = f"(ctypes.c_char * {fld.str_len})"
    else:
        base = fld.type
    return f"{base} * {fld.count}" if fld.count else base.strip("()") if fld.is_str else base


def py_annotation(fld: Field) -> str:
    if fld.type in BASIC:
        base = BASIC[fld.type][4]
    elif fld.is_str:
        return "Sequence[Any]" if fld.count else "bytes"
    else:
        base = fld.type
    return f"Sequence[{base}]" if fld.count else base


def write_python() -> None:
    out = [
        '"""Generated by tools/generate.py"""',
        "from __future__ import annotations",
        "",
        "import ctypes",
        "from typing import Any, Sequence",
        "",
    ]
    for name, value in CONSTS.items():
        out.append(f"{name} = {value}")
    for st in STRUCTS_LIST:
        lay = layout(st.name)
        out += ["", "", f"class {st.name}(ctypes.Structure):", f'    """{st.desc}"""', ""]
        fields = []
        for kind, item, off, size in lay["items"]:
            if kind == "pad":
                fields.append(f'        ("{item}", ctypes.c_uint8 * {size}),')
                continue
            fld = item
            text = doc_line(fld)
            if fld.is_str:
                text += (" Each entry is a c_char array, read it with `.value` (bytes)." if fld.count
                         else " Bytes, decode with `.decode(\"utf-8\", \"replace\")`.")
            out += [f"    {fld.name}: {py_annotation(fld)}", f'    """{text}"""']
            if fld.is_str and fld.count:
                ctype = f"(ctypes.c_char * {fld.str_len}) * {fld.count}"
            elif fld.is_str:
                ctype = f"ctypes.c_char * {fld.str_len}"
            else:
                ctype = py_ctype(fld)
            fields.append(f'        ("{fld.name}", {ctype}),')
        out += ["", "    _fields_ = ["] + fields + ["    ]"]
    out += [""]
    for st in STRUCTS_LIST:
        out.append(f'assert ctypes.sizeof({st.name}) == {layout(st.name)["size"]}, "{st.name} layout"')
    out.append("")
    path = ROOT / "python" / "src" / "ets2la_telemetry" / "_data.py"
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")


def md_escape(text: str) -> str:
    return text.replace("|", "\\|")


def write_markdown() -> None:
    paths: dict[str, str] = {}

    def walk(name: str, path: str) -> None:
        for fld in STRUCTS[name].fields:
            if fld.type in STRUCTS:
                sub = f"{path}{fld.name}" + ("[i]" if fld.count else "")
                paths.setdefault(fld.type, sub)
                walk(fld.type, sub + ".")

    walk("TelemetryData", "")
    values = sum(1 for st in STRUCTS_LIST for f in st.fields)
    out = [
        "# ets2la_telemetry",
        "",
        "_Generated by `tools/generate.py` from `tools/telemetry_spec.txt`._",
        "",
        f"The plugin publishes one **`TelemetryData`** snapshot per game frame, made of {len(STRUCTS_LIST)} structures "
        f"with {values} fields. Every value comes from the official SCS telemetry SDK.",
        "",
        "## How values work",
        "",
        "| Type | Python | C++ | Range | Meaning |",
        "| --- | --- | --- | --- | --- |",
        "| bool | `bool` | `bool` | `False` / `True` | A switch or warning, `True` while it is active. |",
        "| int32 / uint32 | `int` | `int32_t` / `uint32_t` | whole numbers | Counters, indices, gears. Signedness as listed. |",
        "| int64 / uint64 | `int` | `int64_t` / `uint64_t` | whole numbers | Money and clocks. |",
        "| float32 / float64 | `float` | `float` / `double` | real numbers | Physical values in the unit listed. World coordinates are float64, everything else float32. |",
        "| string[N] | `bytes` | `char[N]` | text | UTF-8, zero terminated, at most N-1 characters, longer names are cut off. |",
        "| x N | indexable | `T name[N]` | fixed size array | Entries beyond the real count (for example `wheel_count`) stay 0. |",
        "",
        "**Units:** the SDK units are kept: meters, seconds, liters, kilometers, degrees Celsius, pressure in psi, speeds in m/s. "
        "Angles are **turns** (1.0 = 360 degrees), see `Euler`.",
        "",
        "**Updates:** the plugin publishes at the end of every simulation frame. Channels the game only reports on change keep their last value. "
        "While `game.paused` is `True` most channels stop updating. Configuration values (strings, capacities, wheel layout, job) change only "
        "when the game sends a configuration event, `game.config_changes` counts those.",
        "",
        "**Defaults:** every value is `0` / empty / `False` until the game delivers it, and goes back to that when the game reports it as unavailable.",
        "",
    ]
    for st in STRUCTS_LIST:
        out += [f"## {st.name}", "", st.desc, ""]
        where = paths.get(st.name)
        if where:
            out += [f"Access path: `{where}`", ""]
        out += ["| Name | Type | Unit | Description |", "| --- | --- | --- | --- |"]
        for fld in st.fields:
            out.append(f"| `{fld.name}` | {doc_type(fld)} | {md_escape(fld.unit)} | {md_escape(fld.desc)} |")
        out.append("")
    path = ROOT / "docs" / "TELEMETRY.md"
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")


def own_cfg_id(st: Struct) -> str | None:
    for fld in st.fields:
        if fld.bind and fld.bind[0] == "present":
            return fld.bind[1]
    return None


def has_channels(name: str) -> bool:
    return any((f.bind and f.bind[0] == "ch") or (f.type in STRUCTS and has_channels(f.type)) for f in STRUCTS[name].fields)


def has_config(name: str) -> bool:
    return any((f.bind and f.bind[0] in ("cfg", "present")) or (f.type in STRUCTS and has_config(f.type))
               for f in STRUCTS[name].fields)


def is_event(st: Struct) -> bool:
    return any(f.bind and f.bind[0] in ("ev", "evcount", "evtime") for f in st.fields)


def write_bindings() -> None:
    out = [
        "// Generated by tools/generate.py",
        "#pragma once",
        "",
        "#include <string>",
        "",
        '#include "../../include/ets2la_telemetry/telemetry_data.h"',
        "",
        "namespace ets2la_telemetry {",
        "",
        "constexpr uint32_t kNoIndex = 0xFFFFFFFFu;",
        "",
    ]
    for st in STRUCTS_LIST:
        if not has_channels(st.name):
            continue
        out += [f"template <class R>",
                f"void bind_channels_{st.name}(R& r, {st.name}& o, const std::string& p, uint32_t index = kNoIndex) {{",
                "    (void)p;", "    (void)index;"]
        for fld in st.fields:
            if fld.bind and fld.bind[0] == "ch":
                if fld.count:
                    out.append(f'    for (uint32_t i = 0; i < {fld.count}; ++i) r.channel(p + "{fld.bind[1]}", i, &o.{fld.name}[i]);')
                else:
                    out.append(f'    r.channel(p + "{fld.bind[1]}", index, &o.{fld.name});')
            elif fld.type in STRUCTS and has_channels(fld.type):
                child = STRUCTS[fld.type]
                pref = f'std::string("{child.prefix}")' if child.prefix is not None else "p"
                if fld.count:
                    out.append(f"    for (uint32_t i = 0; i < {fld.count}; ++i) bind_channels_{fld.type}(r, o.{fld.name}[i], {pref}, i);")
                else:
                    out.append(f"    bind_channels_{fld.type}(r, o.{fld.name}, {pref}, index);")
        out += ["}", ""]
    for st in STRUCTS_LIST:
        if st.name == "TelemetryData" or not (has_config(st.name) or is_event(st)):
            continue
        event = is_event(st)
        out.append("template <class R>")
        if event:
            out.append(f"void bind_config_{st.name}(R& r, {st.name}& o) {{")
        else:
            out += [f"void bind_config_{st.name}(R& r, const std::string& id, {st.name}* arr, uint32_t n) {{", "    (void)id;", "    (void)n;"]
        for fld in st.fields:
            b = fld.bind
            if b and b[0] == "present":
                out.append(f"    r.present(id, &arr[0].{fld.name});")
            elif b and b[0] == "evcount":
                evtime = next(x for x in st.fields if x.bind == ("evtime", b[1]))
                out.append(f'    r.counter("{b[1]}", &o.{fld.name}, &o.{evtime.name});')
            elif b and b[0] in ("cfg", "ev"):
                if b[0] == "ev":
                    cid = f'"{b[1]}"'
                else:
                    cid = "id" if b[1] in ("@", own_cfg_id(st)) else f'"{b[1]}"'
                attr = b[2]
                ptr = f"o.{fld.name}" if event else f"arr[0].{fld.name}"
                stride, count = ("0", "1") if event else (f"sizeof({st.name})", "n")
                if fld.is_str and fld.count:
                    out.append(f'    r.attr_str({cid}, "{attr}", {ptr}[0], sizeof({ptr}[0]), sizeof({ptr}[0]), {fld.count});')
                elif fld.is_str:
                    out.append(f'    r.attr_str({cid}, "{attr}", {ptr}, sizeof({ptr}), {stride}, {count});')
                elif fld.count:
                    out.append(f'    r.attr({cid}, "{attr}", &{ptr}[0], sizeof({ptr}[0]), {fld.count});')
                else:
                    out.append(f'    r.attr({cid}, "{attr}", &{ptr}, {stride}, {count});')
            elif fld.type in STRUCTS and has_config(fld.type) and not event:
                child = STRUCTS[fld.type]
                ids = {x.bind[1] for x in child.fields if x.bind and x.bind[0] == "cfg"}
                cid = f'"{sorted(ids)[0]}"' if ids and "@" not in ids else "id"
                if fld.count:
                    out.append(f"    bind_config_{fld.type}(r, {cid}, &arr[0].{fld.name}[0], {fld.count});")
                else:
                    out.append(f"    bind_config_{fld.type}(r, {cid}, &arr[0].{fld.name}, 1);")
        out += ["}", ""]
    out.append("}")
    path = ROOT / "src" / "dll" / "bindings.h"
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()